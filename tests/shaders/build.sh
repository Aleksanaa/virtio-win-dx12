#!/usr/bin/env bash
# SPDX-License-Identifier: MIT
# Compiles the test shaders with dxc (signed DXIL containers) into C++ headers, one per .hlsl file. Needs dxc on
# PATH, e.g.
#   nix shell nixpkgs#directx-shader-compiler -c tests/shaders/build.sh
set -euo pipefail
cd "$(dirname "$0")"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# header: file entry:profile...
build() {
    local src=$1 out=${1%.hlsl}_dxil.h
    shift
    {
        echo "// SPDX-License-Identifier: MIT"
        echo "// Generated by build.sh from $src with $(dxc --version 2>&1 | head -1). Do not edit."
        echo "#pragma once"
        echo "#include <cstdint>"
        for spec in "$@"; do
            local entry=${spec%%:*}
            dxc -nologo -T "${spec##*:}" -E "$entry" -Fo "$tmp/$entry.dxil" "$src" >/dev/null
            echo "alignas(4) inline const uint8_t k_${entry}[] = {"
            od -An -v -t x1 "$tmp/$entry.dxil" | sed -E 's/ ([0-9a-f]{2})/0x\1,/g; s/^/   /'
            echo "};"
        done
    } > "$out"
    echo "wrote $out"
}

build triangle.hlsl vs_corner:vs_6_0 vs_buffer:vs_6_0 ps_color:ps_6_0
build textured.hlsl vs_fullscreen:vs_6_0 ps_textured:ps_6_0
build depth.hlsl vs_flat:vs_6_0 ps_flat:ps_6_0
