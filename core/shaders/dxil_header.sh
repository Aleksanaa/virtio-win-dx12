# build file entry:profile...: compiles each entry point of file.hlsl (signed DXIL containers) into
# file_dxil.h, as arrays k_<entry>.
build() {
    local src=$1 out=${1%.hlsl}_dxil.h tmp
    shift
    tmp=$(mktemp -d)
    {
        echo "// SPDX-License-Identifier: MIT"
        echo "// Generated by build.sh from $src with $(dxc --version 2>&1 | head -1). Do not edit."
        echo "#pragma once"
        echo "#include <cstdint>"
        for spec in "$@"; do
            local entry=${spec%%:*}
            dxc -nologo -T "${spec##*:}" -E "$entry" -Fo "$tmp/$entry.dxil" "$src" >/dev/null
            echo "alignas(4) inline const uint8_t k_${entry}[] = {"
            od -An -v -t x1 "$tmp/$entry.dxil" | sed -E 's/ ([0-9a-f]{2})/0x\1,/g; s/^/   /'
            echo "};"
        done
    } > "$out"
    rm -rf "$tmp"
    echo "wrote $out"
}
